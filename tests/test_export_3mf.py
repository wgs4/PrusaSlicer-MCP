"""Exported 3MF projects carry the bed's full configuration in comment form."""

import hashlib
import re
import shutil
import zipfile
from pathlib import Path

import pytest
from conftest import MODELS
from profiles import MK4S

from prusaslicer_mcp import cli_engine as ce
from prusaslicer_mcp.cli_engine import CliEngine
from prusaslicer_mcp.runner import run_cli
from prusaslicer_mcp.verify import read_effective_config

CUBE = MODELS / "20mm_cube.obj"
CONFIG_ENTRY = "Metadata/Slic3r_PE.config"
CONFIG_LINE = re.compile(r"^; ([a-z0-9_]+) = (.*)$")
_VENDOR_CANDIDATES = (
    Path("/Applications/PrusaSlicer.app/Contents/Resources/profiles/PrusaResearch.ini"),
)


def _vendor_ini(install) -> Path:
    candidates = []
    if install.resources is not None:
        candidates.append(install.resources / "profiles" / "PrusaResearch.ini")
    exe = install.console.resolve()
    candidates.append(exe.parent.parent / "Resources" / "profiles" / "PrusaResearch.ini")
    candidates.append(exe.parent / "resources" / "profiles" / "PrusaResearch.ini")
    candidates.extend(_VENDOR_CANDIDATES)
    for path in candidates:
        if path.is_file():
            return path
    pytest.skip("PrusaSlicer vendor bundle not found")


def _synthetic_datadir(install, tmp_path: Path) -> Path:
    """A temp datadir with the stock vendor bundle and one FFF printer enabled.

    The user's live datadir is never read or written.
    """
    datadir = tmp_path / "datadir"
    (datadir / "vendor").mkdir(parents=True)
    shutil.copy(_vendor_ini(install), datadir / "vendor" / "PrusaResearch.ini")
    (datadir / "PrusaSlicer.ini").write_text("[vendor:PrusaResearch]\nmodel:MK4S = 0.4\n", encoding="utf-8")
    return datadir


def _tree_digest(root: Path) -> dict[str, str]:
    digest = {}
    for path in sorted(p for p in root.rglob("*") if p.is_file() and not p.is_symlink()):
        digest[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return digest


def _project_config(path: Path) -> str:
    with zipfile.ZipFile(path) as archive:
        return archive.read(CONFIG_ENTRY).decode("utf-8")


def _config_values(text: str) -> dict[str, str]:
    values = {}
    for line in text.splitlines():
        if not line or line.startswith("; generated by PrusaSlicer"):
            continue
        match = CONFIG_LINE.match(line)
        assert match, f"config line is not '; key = value': {line!r}"
        values[match.group(1)] = match.group(2)
    return values


def test_config_comment_form_prefixes_keys_and_rewrites_the_header():
    text = (
        "# generated by PrusaSlicer 2.9.7 on 2026-01-01 at 00:00:00 UTC\n"
        "fill_density = 25%\n"
        "printer_settings_id = Example Printer\n"
    )
    out = ce.config_to_project_comment(text)
    assert out.splitlines()[0] == "; generated by PrusaSlicer 2.9.7 on 2026-01-01 at 00:00:00 UTC"
    values = _config_values(out)
    assert values["fill_density"] == "25%"
    assert values["printer_settings_id"] == "Example Printer"


@pytest.mark.real_slicer
@pytest.mark.slicer
def test_export_3mf_embeds_comment_form_config(install, tmp_path):
    datadir = _synthetic_datadir(install, tmp_path)
    before = _tree_digest(datadir)
    engine = CliEngine(install, datadir, tmp_path / "work")
    engine.select_profiles(*MK4S[:2], [MK4S[2]])
    engine.set_setting("fill_density", "25%")
    engine.add_model(CUBE)

    out = engine.export_3mf(tmp_path / "plate.3mf")

    assert _tree_digest(datadir) == before
    assert out.is_file()
    text = _project_config(out)
    assert "; fill_density = 25%" in text.splitlines()
    values = _config_values(text)
    assert values["fill_density"] == "25%"
    assert values["printer_settings_id"] == MK4S[0]
    assert values["print_settings_id"] == MK4S[1]
    assert values["filament_settings_id"].strip('"') == MK4S[2]


@pytest.mark.real_slicer
@pytest.mark.slicer
def test_exported_3mf_slices_with_no_profile_arguments(install, tmp_path):
    datadir = _synthetic_datadir(install, tmp_path)
    engine = CliEngine(install, datadir, tmp_path / "work")
    engine.select_profiles(*MK4S[:2], [MK4S[2]])
    engine.set_setting("fill_density", "25%")
    engine.add_model(CUBE)
    project = engine.export_3mf(tmp_path / "plate.3mf")

    gcode = tmp_path / "from_project.gcode"
    run_cli(
        install,
        ["--datadir", datadir, "--export-gcode", "--no-binary-gcode", "-o", gcode, project],
    )
    assert read_effective_config(gcode)["fill_density"] == "25%"
